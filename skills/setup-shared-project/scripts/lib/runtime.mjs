import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import crypto from 'node:crypto'
import { hash, json, atomicWrite, readJSON, relative, inside, physical, cacheRoot, resolveWorkspace } from './core.mjs'
import { acquireLock } from './lock.mjs'
import { ensureNode, satisfies, run } from './node.mjs'

const protectedParts = new Set(['node_modules','.git','.shared-project','.runtime'])
const reservedPart = part => protectedParts.has(part) || part.startsWith('.shared-') || /\.shared-(?:staging|previous|export\.lock(?:\.acquire)?)$/.test(part)
const inventory = '.shared-source-files.json'
const excluded = (rel, app) => rel.split('/').some(reservedPart) ||
  [...(app.exclude || []), ...(app.buildOutput ? [app.buildOutput]:[])].some(p => rel === p || rel.startsWith(p+'/'))

export function runtimeDirectory(config, app, task, { platform = process.platform, arch = process.arch, nodeVersion = process.versions.node,
  abi = process.versions.modules, env = process.env, home = os.homedir() } = {}) {
  const p = platform === 'win32' ? path.win32 : path.posix
  const role = ['export','preview','build'].includes(task) ? 'build':task
  return p.join(cacheRoot({platform,env,home}),'projects',config.projectId,hash(config.paths.project).slice(0,16),
    `${platform}-${arch}-node${nodeVersion.split('.')[0]}-abi${abi}`,app,role)
}
export function claimSource(directory, source) {
  const stat = fs.statSync(source), real = fs.realpathSync(source)
  const identity = { real, device:String(stat.dev), inode:String(stat.ino), birth:stat.birthtimeMs }
  const file = path.join(directory,'.shared-owner.json')
  if (fs.existsSync(file)) {
    const previous = readJSON(file)
    const sameFile = identity.inode !== '0' && identity.device === previous.device && identity.inode === previous.inode && identity.birth === previous.birth
    if (previous.real !== real && !sameFile) throw new Error('Projektkennung kollidiert mit einer anderen Quellinstanz. Für unabhängige Kopien neue projectId vergeben; Worktrees brauchen einen eigenen logischen Projektpfad.')
  } else atomicWrite(file,json(identity))
}
export function syncSources(source, destination, app) {
  if (inside(source,destination) || inside(destination,source)) throw new Error('Quelle und Laufzeit müssen getrennt liegen.')
  const manifestPath = path.join(destination,inventory)
  const previous = fs.existsSync(manifestPath) ? readJSON(manifestPath) : []
  for (const rel of previous) {
    relative(rel)
    if (rel.split('/').some(reservedPart)) throw new Error('Ungültiges Laufzeitinventar: reservierter Pfad')
  }
  const files = new Map()
  const collect = rel => {
    if (rel !== '.' && excluded(rel,app)) return
    const from = path.resolve(source,rel), stat = fs.lstatSync(from)
    if (stat.isSymbolicLink()) throw new Error(`Symlink in Quellauswahl nicht unterstützt: ${rel}. Explizit auflösen oder ausschließen.`)
    if (stat.isDirectory()) { for (const name of fs.readdirSync(from).sort()) collect(rel === '.' ? name : `${rel}/${name}`); return }
    if (!stat.isFile()) throw new Error(`Keine reguläre Quelldatei: ${rel}`)
    let bytes = fs.readFileSync(from)
    if (rel === 'package.json') {
      const manifest = JSON.parse(bytes)
      if (manifest.workspaces) throw new Error('npm-Workspaces brauchen ein eigenes Profil; V1 unterstützt eigenständige App-Manifeste.')
      // Only remove wrappers generated by this toolkit. All user scripts/hooks survive.
      for (const [key,value] of Object.entries(manifest.scripts || {})) {
        if (key.startsWith('shared:') && /\.shared-project\/tools\/cli\.mjs/.test(value)) delete manifest.scripts[key]
      }
      if (Object.values(manifest.scripts || {}).some(v => /\.shared-project\/tools\/cli\.mjs|npm\s+run\s+shared:/.test(v))) throw new Error('Rekursiver Wrapper in eigenem npm-Skript. Befehl im Einrichtungsplan entkoppeln.')
      for (const dependencies of [manifest.dependencies,manifest.devDependencies,manifest.optionalDependencies]) {
        for (const value of Object.values(dependencies || {})) if (/^(file:|link:)/.test(value)) {
          const rel = value.replace(/^(file:|link:)/,''); relative(rel,'Lokale Paketabhängigkeit',true)
        }
      }
      bytes = Buffer.from(json(manifest))
    }
    files.set(rel,bytes)
  }
  for (const rel of new Set([...app.sources,'package.json','package-lock.json', ...(fs.existsSync(path.join(source,'.npmrc')) ? ['.npmrc']:[])])) {
    relative(rel,'Quelle',true)
    if (!fs.existsSync(path.join(source,rel))) { if (['package.json','package-lock.json'].includes(rel)) throw new Error(`npm-Profil braucht ${rel}`); continue }
    collect(rel)
  }
  fs.mkdirSync(destination,{recursive:true})
  // Remove retired files first; this also permits file/directory transitions.
  for (const rel of previous) if (!files.has(rel)) {
    const target = path.join(destination,rel)
    if (!inside(physical(destination),physical(target))) throw new Error('Ungültiges lokales Löschziel.')
    if (fs.existsSync(target) && fs.lstatSync(target).isFile()) fs.rmSync(target,{force:true})
    let parent = path.dirname(target)
    while (parent !== destination && inside(destination,parent) && fs.existsSync(parent) && fs.readdirSync(parent).length === 0) { fs.rmdirSync(parent); parent = path.dirname(parent) }
  }
  for (const [rel,bytes] of files) {
    const target = path.join(destination,rel)
    if (!inside(physical(destination),physical(target))) throw new Error(`Lokales Ziel verlässt die Laufzeit: ${rel}`)
    if (fs.existsSync(target) && fs.lstatSync(target).isDirectory()) {
      if (fs.readdirSync(target).length) throw new Error(`Nicht verwaltete lokale Dateien verhindern Verzeichniswechsel: ${rel}`)
      fs.rmdirSync(target)
    }
    if (!fs.existsSync(target) || !bytes.equals(fs.readFileSync(target))) atomicWrite(target,bytes)
  }
  atomicWrite(manifestPath,json([...files.keys()].sort()))
  return files
}
export function restartFingerprint(source, app, root) {
  return hash(json(['package.json','package-lock.json','.npmrc',...(app.restart || [])].map(rel => [rel,
    fs.existsSync(path.join(source,rel)) ? hash(fs.readFileSync(path.join(source,rel))) : null])) + fs.readFileSync(path.join(root,'shared-project.json'),'utf8'))
}
export function devSynchronizer(source, runtime, app, root, warn = console.error) {
  const initial = restartFingerprint(source,app,root)
  let warned = false
  return () => {
    if (restartFingerprint(source,app,root) !== initial) {
      if (!warned) warn('Paket-, Lock- oder Konfigurationsänderung: Dev neu starten, damit Installation und Konfiguration konsistent bleiben.')
      warned = true; return false
    }
    syncSources(source,runtime,app); return true
  }
}
export function stagedExport(from, target, { beforeSwap, afterBackup } = {}) {
  if (!fs.existsSync(from) || !fs.statSync(from).isDirectory()) throw new Error('Lokales Build-Ergebnis fehlt.')
  if (inside(from,target) || inside(target,from)) throw new Error('Build- und Exportziel überlappen.')
  fs.mkdirSync(path.dirname(target),{recursive:true})
  const unlock = acquireLock(`${target}.shared-export.lock`)
  // Stable recovery paths permit recovery after process/machine termination.
  const staging = `${target}.shared-staging`, backup = `${target}.shared-previous`
  try {
    if (!fs.existsSync(target) && fs.existsSync(backup)) fs.renameSync(backup,target)
    if (fs.existsSync(target) && fs.existsSync(backup)) fs.rmSync(backup,{recursive:true})
    fs.rmSync(staging,{recursive:true,force:true})
    fs.cpSync(from,staging,{recursive:true,dereference:false,filter:src => {
      if (fs.lstatSync(src).isSymbolicLink()) throw new Error('Symlink im Build-Ergebnis nicht exportieren.')
      return true
    }})
    beforeSwap?.()
    if (fs.existsSync(target)) fs.renameSync(target,backup)
    try { afterBackup?.(); fs.renameSync(staging,target) }
    catch (e) { if (!fs.existsSync(target) && fs.existsSync(backup)) fs.renameSync(backup,target); throw e }
    fs.rmSync(backup,{recursive:true,force:true})
  } finally { fs.rmSync(staging,{recursive:true,force:true}); unlock() }
}
export async function execute(root, config, name, task, extra = []) {
  const app = config.apps[name]
  if (!app) throw new Error(`Unbekannte Anwendung: ${name}`)
  const workspace = resolveWorkspace({root,settings:config}), source = path.resolve(root,app.path)
  if (!inside(physical(root),physical(source))) throw new Error('Anwendung verlässt das Projekt.')
  const cache = path.resolve(cacheRoot())
  if (inside(physical(workspace.sharedRoot),physical(cache))) throw new Error('Der Laufzeitcache muss außerhalb der gemeinsamen Basis liegen.')
  if (task === 'guard') {
    if (fs.existsSync(path.join(source,'node_modules'))) throw new Error('node_modules im gemeinsamen Quellordner gefunden. Sichere/entferne diese Installation bewusst; nutze danach shared:setup.')
    throw new Error('Installiere mit shared:setup in die lokale Laufzeit. Manuelles npm ci/install im Quellordner vermeiden; Hooks bieten keinen vollständigen Schutz.')
  }
  if (!['info','setup','export',...Object.keys(app.commands)].includes(task)) throw new Error(`Aufgabe nicht konfiguriert: ${task}`)
  const toolBase = path.join(cache,'tools',process.platform,process.arch)
  const node = await ensureNode(app.runtime,toolBase)
  const abi = node.bootstrapped ? (await run(node.executable,['-p','process.versions.modules'],{quiet:true})).trim() : process.versions.modules
  const runtime = runtimeDirectory(config,name,task,{nodeVersion:node.version,abi})
  if (task === 'info') return { ...workspace, source, runtime, node }
  if (fs.existsSync(path.join(source,'node_modules'))) throw new Error('Gemeinsame node_modules gefunden. Bewusst lokal sichern/entfernen, bevor die isolierte Laufzeit startet.')
  const unlock = acquireLock(path.join(runtime,'.shared-runner.lock'))
  let timer
  try {
    claimSource(runtime,root)
    const startingSource = restartFingerprint(source,app,root)
    syncSources(source,runtime,app)
    const manifest = readJSON(path.join(runtime,'package.json'))
    if (manifest.engines?.node && !satisfies(node.version,manifest.engines.node)) throw new Error(`Node ${node.version} erfüllt package.json engines.node nicht.`)
    const env = { ...process.env, SHARED_ROOT:workspace.sharedRoot, SHARED_PROJECT_ROOT:root,
      PATH:path.dirname(node.executable)+path.delimiter+(process.env.PATH || ''), npm_config_cache:path.join(cache,'npm',config.projectId,process.platform,process.arch,node.version.split('.')[0],name,task) }
    for (const [key,value] of Object.entries(app.envPaths || {})) env[key] = workspace.paths[value]
    const fingerprint = hash(['package.json','package-lock.json','.npmrc',...(app.restart || [])].map(file => fs.existsSync(path.join(runtime,file)) ? fs.readFileSync(path.join(runtime,file)) : '').join('\0')+json({node:node.version,abi,platform:process.platform,arch:process.arch,envPaths:app.envPaths,runtime:app.runtime}))
    const stamp = path.join(runtime,'.shared-installed')
    if (!fs.existsSync(stamp) || fs.readFileSync(stamp,'utf8') !== fingerprint ||
      ((Object.keys(manifest.dependencies || {}).length+Object.keys(manifest.devDependencies || {}).length > 0) && !fs.existsSync(path.join(runtime,'node_modules')))) {
      fs.rmSync(stamp,{force:true})
      await run(node.executable,[node.npm,'ci','--no-audit','--no-fund','--cache',env.npm_config_cache],{cwd:runtime,env})
      atomicWrite(stamp,fingerprint)
    }
    if (startingSource !== restartFingerprint(source,app,root)) throw new Error('Paket- oder Konfigurationsquelle während der Einrichtung geändert. Aufgabe erneut starten.')
    const command = async (action, args = []) => {
      const c = app.commands[action]
      if (!c) throw new Error(`Aufgabe nicht konfiguriert: ${action}`)
      if (c.script) {
        if (!manifest.scripts?.[c.script]) throw new Error(`Paket-Skript fehlt: ${c.script}`)
        await run(node.executable,[node.npm,'run',c.script,'--',...args],{cwd:runtime,env})
      } else await run(node.executable,[...c.node,...args],{cwd:runtime,env})
    }
    if (task === 'setup') return { runtime }
    if (task === 'dev') {
      const tick = devSynchronizer(source,runtime,app,root)
      timer = setInterval(() => { try { tick() } catch (e) { console.error(`Quellabgleich: ${e.message}. Dev neu starten.`) } },500)
    }
    if (task === 'preview') {
      if (!app.buildOutput) throw new Error('buildOutput fehlt für Preview.')
      // Preview always builds this snapshot, avoiding an obsolete build after source sync.
      await command('build'); await command('preview',extra)
    } else if (task === 'export') {
      if (!app.buildOutput || !app.exportPath) throw new Error('buildOutput/exportPath fehlen.')
      await command('build',extra)
      const target = path.resolve(workspace.sharedRoot,app.exportPath)
      const inSource = inside(physical(source),physical(target)), relTarget = path.relative(source,target).split(path.sep).join('/')
      if (!inside(physical(workspace.sharedRoot),physical(target)) || inside(physical(target),physical(source)) ||
        (inSource && !excluded(relTarget,app))) throw new Error('Exportziel muss innerhalb der Basis liegen und aus der Quellauswahl ausgeschlossen sein; es darf keine Quelle ersetzen.')
      stagedExport(path.join(runtime,app.buildOutput),target)
    } else await command(task,extra)
    return { runtime }
  } finally { if (timer) clearInterval(timer); unlock() }
}
